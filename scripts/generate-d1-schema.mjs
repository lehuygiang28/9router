#!/usr/bin/env node
// Generate a single .d1-schema.sql file from src/lib/db/schema.js.
// Loads schema via a data: URL so Node treats it as ESM without renaming
// schema.js or setting package.json "type":"module".
// Output: wrangler d1 execute --file=.d1-schema.sql (gitignored).

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const repoRoot = resolve(__dirname, "..");

const schemaPath = resolve(repoRoot, "src/lib/db/schema.js");
const schemaSource = readFileSync(schemaPath, "utf8");
const schemaModuleUrl = `data:text/javascript;charset=utf-8,${encodeURIComponent(schemaSource)}`;
const { TABLES, SCHEMA_VERSION, buildCreateTableSql } = await import(schemaModuleUrl);

const lines = [
  "-- AUTO-GENERATED by scripts/generate-d1-schema.mjs",
  "-- Do not edit by hand. Re-generate with `npm run migrate:cf:generate`.",
  "-- Idempotent: safe to run on existing D1 databases.",
  "",
];

for (const [name, def] of Object.entries(TABLES)) {
  lines.push(`-- table: ${name}`);
  lines.push(`${buildCreateTableSql(name, def)};`);
  for (const idx of def.indexes || []) {
    lines.push(`${idx};`);
  }
  lines.push("");
}

// Seed schemaVersion so runtime runVersionedMigrations() short-circuits.
lines.push("-- seed schemaVersion so runtime migrate skips versioned upgrades");
lines.push(
  `INSERT OR REPLACE INTO _meta (key, value) VALUES ('schemaVersion', '${SCHEMA_VERSION}');`,
);
lines.push("");

lines.push(
  "-- default settings row: empty JSON → password unset → INITIAL_PASSWORD / 123456",
);
lines.push(`INSERT OR IGNORE INTO settings (id, data) VALUES (1, '{}');`);
lines.push("");

const outPath = resolve(repoRoot, ".d1-schema.sql");
mkdirSync(dirname(outPath), { recursive: true });
writeFileSync(outPath, lines.join("\n"), "utf8");

const tableCount = Object.keys(TABLES).length;
const indexCount = Object.values(TABLES).reduce(
  (n, def) => n + (def.indexes?.length || 0),
  0,
);
console.log(
  `[migrate] generated .d1-schema.sql (${tableCount} tables, ${indexCount} indexes, schemaVersion=${SCHEMA_VERSION})`,
);
