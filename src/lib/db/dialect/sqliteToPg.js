function quoteCamelCase(code) {
  return code.replace(/\b([A-Za-z_][A-Za-z0-9_]*)\b/g, (ident) => {
    if (!/[A-Z]/.test(ident)) return ident;
    if (SQL_KEYWORDS.has(ident.toUpperCase()) && ident === ident.toUpperCase()) return ident;
    return `"${ident}"`;
  });
}

function rewritePlaceholders(sql) {
  let n = 0;
  return mapCodeAndStrings(sql, (code) => code.replace(/\?/g, () => `$${++n}`));
}

function rejectUnsupported(sql) {
  const lower = sql.toLowerCase();
  if (/\bdatetime\s*\(/.test(lower)) throw new UnsupportedSqliteSql(sql, "datetime()");
  if (/\bstrftime\s*\(/.test(lower)) throw new UnsupportedSqliteSql(sql, "strftime()");
  if (/\bjson_each\s*\(/.test(lower)) throw new UnsupportedSqliteSql(sql, "json_each()");
}

export function translateSqliteToPg(sql) {
  const trimmed = String(sql).trim();
  rejectUnsupported(trimmed);

  const pragmaInfo = trimmed.match(/^PRAGMA\s+table_info\s*\(\s*([A-Za-z_][\w]*)\s*\)\s*;?$/i);
  if (pragmaInfo) return { kind: "pragma_table_info", table: pragmaInfo[1] };
  if (/^PRAGMA\b/i.test(trimmed)) return { kind: "pragma_noop" };

  if (/\bsqlite_master\b/i.test(trimmed)) return { kind: "sqlite_master" };
  if (/^\s*ATTACH\s+DATABASE\b/i.test(trimmed) || /^\s*DETACH\s+DATABASE\b/i.test(trimmed)) {
    return { kind: "skip_backup" };
  }

  let out = trimmed;
  out = rewriteJsonExtract(out);
  out = applyInsertOrIgnore(out);
  out = rewriteInsertOrReplace(out);
  out = finalizeOrReplace(out);
  // leftover marker means VALUES parsing failed
  if (/__OR_REPLACE__/.test(out)) {
    throw new UnsupportedSqliteSql(sql, "INSERT OR REPLACE rewrite failed");
  }
  out = rewriteDdl(out);
  out = mapCodeAndStrings(out, quoteCamelCase);
  out = rewritePlaceholders(out);
  return { kind: "sql", text: out };
}
